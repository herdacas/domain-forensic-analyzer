/* Domain Forensic Analyzer demo: replays a stored scan in a fake terminal and
   mirrors its progress in the inspector. Data comes from data/scenarios.js
   (generated by scripts/build_demo.py). */
(function () {
  "use strict";

  var DATA = window.DFA_DEMO;
  var SLUGS = { A: "linux-direct", B: "linux-vpn", C: "windows-direct", D: "windows-vpn" };
  var REDUCED_MOTION = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  // Base pacing in ms at 1x speed.
  var PACE = { typeChar: 45, beforeEnter: 350, metadata: 900, headerLine: 22, module: 520, reportLine: 14 };

  function $(id) { return document.getElementById(id); }

  function el(tag, attrs, children) {
    var node = document.createElement(tag);
    if (attrs) {
      Object.keys(attrs).forEach(function (key) {
        if (key === "text") node.textContent = attrs[key];
        else if (key === "html") node.innerHTML = attrs[key];
        else node.setAttribute(key, attrs[key]);
      });
    }
    (children || []).forEach(function (child) { if (child) node.appendChild(child); });
    return node;
  }

  function escapeHtml(text) {
    return text.replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }

  // ---------------------------------------------------------------------------
  // ANSI SGR -> HTML (only the codes src/utils/colors.py emits)
  // ---------------------------------------------------------------------------
  var ANSI = {
    1: "b", 2: "dim", 4: "u",
    90: "gray", 91: "red", 92: "green", 93: "yellow", 94: "blue", 95: "purple", 96: "cyan", 97: "white",
    41: "bg-red", 42: "bg-green", 43: "bg-yellow", 44: "bg-blue"
  };

  function ansiToHtml(line) {
    var out = "";
    var classes = [];
    var re = /\x1b\[([0-9;]*)m/g;
    var last = 0;
    var match;
    function flush(text) {
      if (!text) return;
      var safe = escapeHtml(text);
      out += classes.length
        ? '<span class="' + classes.map(function (c) { return "a-" + c; }).join(" ") + '">' + safe + "</span>"
        : safe;
    }
    while ((match = re.exec(line))) {
      flush(line.slice(last, match.index));
      last = re.lastIndex;
      var codes = match[1] === "" ? [0] : match[1].split(";").map(Number);
      codes.forEach(function (code) {
        if (code === 0) { classes = []; return; }
        var cls = ANSI[code];
        if (!cls) return;
        if (code >= 90) classes = classes.filter(function (c) { return !/^(gray|red|green|yellow|blue|purple|cyan|white)$/.test(c); });
        classes.push(cls);
      });
    }
    flush(line.slice(last));
    return out;
  }

  function splitLines(text) {
    var lines = text.split("\n");
    if (lines.length && lines[lines.length - 1] === "") lines.pop();
    return lines;
  }

  // ---------------------------------------------------------------------------
  // Formatting helpers
  // ---------------------------------------------------------------------------
  function formatDate(iso) {
    var d = new Date(iso + "Z");
    if (isNaN(d)) return iso;
    return d.toISOString().slice(0, 16).replace("T", " ") + " UTC";
  }

  function networkLabel(s) {
    return s.vpn ? "VPN" + (s.vpn_country ? " (exit " + s.vpn_country + ")" : "") : "Direct";
  }

  function vpnSignal(opsec) {
    if (opsec.vpn_signal === "tunnel_interface") return "Tunnel interface " + opsec.tunnel_interface;
    if (opsec.vpn_signal === "rdns") return "Provider rDNS match";
    return "None observed";
  }

  function topology(opsec) {
    return opsec.behind_nat ? "Behind NAT" : "Direct connection";
  }

  // ---------------------------------------------------------------------------
  // Replay engine
  // ---------------------------------------------------------------------------
  var terminal = $("terminal");
  var state = { scenario: null, steps: [], index: 0, timer: null, playing: false, followScroll: true };

  function speed() { return Number($("speed").value) || 1; }

  function promptParts(s) {
    if (s.os === "Windows") return { user: "PS ", path: "C:\\Users\\analyst\\domain-forensic-analyzer", end: "> " };
    return { user: "analyst@" + s.analyst.system.hostname + ":", path: "~/domain-forensic-analyzer", end: "$ " };
  }

  function addLine(html, cls) {
    var line = el("div", { "class": "line" + (cls ? " " + cls : "") });
    line.innerHTML = html;
    terminal.appendChild(line);
    return line;
  }

  function scrollToEnd() {
    if (state.followScroll) terminal.scrollTop = terminal.scrollHeight;
  }

  function buildSteps(s) {
    var steps = [];
    var p = promptParts(s);
    var promptHtml = '<span class="prompt">' + escapeHtml(p.user) + '</span><span class="prompt-path">' +
      escapeHtml(p.path) + "</span>" + escapeHtml(p.end);
    var cmdLine;
    var command = s.terminal.command;

    steps.push({ delay: 0, run: function () {
      cmdLine = addLine(promptHtml + '<span class="cmd"></span><span class="cursor"></span>');
    } });
    for (var i = 1; i <= command.length; i++) {
      (function (n) {
        steps.push({ delay: PACE.typeChar, typing: true, run: function () {
          cmdLine.querySelector(".cmd").textContent = command.slice(0, n);
        } });
      })(i);
    }
    steps.push({ delay: PACE.beforeEnter, run: function () {
      var cursor = cmdLine.querySelector(".cursor");
      if (cursor) cursor.remove();
    } });

    var header = splitLines(s.terminal.header);
    var metaLine;
    steps.push({ delay: 60, run: function () {
      metaLine = addLine(escapeHtml("Collecting forensic metadata...") + '<span class="spinner"> ⠋</span>');
    } });
    steps.push({ delay: PACE.metadata, run: function () {
      metaLine.innerHTML = ansiToHtml(header[0]);
    } });
    header.slice(1).forEach(function (text) {
      steps.push({ delay: PACE.headerLine, run: function () { addLine(ansiToHtml(text)); } });
    });

    steps.push({ delay: 200, run: function () { addLine(""); addLine("Starting analysis..."); } });

    var progress = s.terminal.progress.lines;
    progress.forEach(function (mod, idx) {
      var line;
      var prefix = "   [" + (idx + 1) + "/" + progress.length + "] " + mod.label + "...";
      steps.push({ delay: 120, run: function () {
        line = addLine(escapeHtml(prefix) + '<span class="spinner"> ⠋</span>');
        setModuleState(mod.module, "running");
      } });
      steps.push({ delay: PACE.module, run: function () {
        line.textContent = prefix + " " + mod.status;
        setModuleState(mod.module, mod.status);
      } });
    });
    steps.push({ delay: 160, run: function () { addLine(escapeHtml(s.terminal.progress.done)); } });

    splitLines(s.terminal.report + s.terminal.footer).forEach(function (text) {
      steps.push({ delay: PACE.reportLine, run: function () { addLine(ansiToHtml(text)); } });
    });

    steps.push({ delay: 300, run: function () {
      addLine(promptHtml + '<span class="cursor"></span>');
    } });
    return steps;
  }

  function updateProgress() {
    var pct = state.steps.length ? (state.index / state.steps.length) * 100 : 0;
    $("progress-fill").style.width = pct.toFixed(1) + "%";
  }

  function setPlaying(playing) {
    state.playing = playing;
    var btn = $("btn-play");
    var finished = state.index >= state.steps.length;
    btn.textContent = playing ? "Pause" : (finished ? "Replay" : "Play");
  }

  function tick() {
    state.timer = null;
    if (!state.playing) return;
    if (state.index >= state.steps.length) { setPlaying(false); return; }
    var step = state.steps[state.index++];
    step.run();
    updateProgress();
    scrollToEnd();
    var next = state.steps[state.index];
    if (!next) { setPlaying(false); return; }
    // Typing keeps a human pace; everything else follows the speed setting.
    var wait = next.typing ? next.delay / Math.min(speed(), 2) : next.delay / speed();
    state.timer = window.setTimeout(tick, wait);
  }

  function play() {
    if (state.index >= state.steps.length) { restart(); return; }
    setPlaying(true);
    if (!state.timer) tick();
  }

  function pause() {
    if (state.timer) window.clearTimeout(state.timer);
    state.timer = null;
    setPlaying(false);
  }

  function finish() {
    if (state.timer) window.clearTimeout(state.timer);
    state.timer = null;
    while (state.index < state.steps.length) state.steps[state.index++].run();
    updateProgress();
    setPlaying(false);
  }

  function restart() {
    pause();
    terminal.textContent = "";
    state.followScroll = true;
    state.steps = buildSteps(state.scenario);
    state.index = 0;
    resetModules();
    updateProgress();
    if (REDUCED_MOTION) {
      finish();
      terminal.scrollTop = 0;
    } else {
      play();
    }
  }

  terminal.addEventListener("scroll", function () {
    var nearBottom = terminal.scrollHeight - terminal.scrollTop - terminal.clientHeight < 40;
    state.followScroll = nearBottom;
  });

  // ---------------------------------------------------------------------------
  // Inspector
  // ---------------------------------------------------------------------------
  function facts(container, rows) {
    container.textContent = "";
    rows.forEach(function (row) {
      container.appendChild(el("dt", { text: row[0] }));
      container.appendChild(el("dd", { text: row[1] }));
    });
  }

  function resetModules() {
    var list = $("module-list");
    list.textContent = "";
    state.scenario.modules.forEach(function (mod) {
      list.appendChild(el("li", { "data-module": mod.id }, [
        el("span", { "class": "name", text: mod.label }),
        el("span", { "class": "state", "data-state": "pending", text: "QUEUED" })
      ]));
    });
    updateModuleCount();
  }

  function setModuleState(id, value) {
    var badge = document.querySelector('#module-list li[data-module="' + id + '"] .state');
    if (!badge) return;
    badge.setAttribute("data-state", value);
    badge.textContent = value === "running" ? "RUNNING" : value;
    updateModuleCount();
  }

  function updateModuleCount() {
    var badges = document.querySelectorAll("#module-list .state");
    var done = 0;
    var ok = 0;
    badges.forEach(function (b) {
      var v = b.getAttribute("data-state");
      if (v !== "pending" && v !== "running") done++;
      if (v === "COMPLETE") ok++;
    });
    $("module-count").textContent = done < badges.length
      ? done + " of " + badges.length + " finished"
      : ok + " of " + badges.length + " complete";
  }

  function renderInspector(s) {
    var r = s.report;
    $("session-id").textContent = s.session_id;
    facts($("session-facts"), [
      ["Target", s.domain],
      ["Scanned", formatDate(s.scanned_at)],
      ["Duration", s.scan_duration_seconds.toFixed(1) + " s"],
      ["Platform", s.os + " (" + s.analyst.system.architecture + ")"],
      ["Network", networkLabel(s)],
      ["Hosting", (r.infrastructure && r.infrastructure.provider_name || "unknown") +
        (r.dns_info && r.dns_info.ipv4 ? " · " + r.dns_info.ipv4 : "")]
    ]);

    var level = (r.overall_risk_level || "unknown").toLowerCase();
    var pill = $("risk-pill");
    pill.setAttribute("data-level", level);
    pill.textContent = level.toUpperCase() + " · " + Number(r.risk_score).toFixed(1) + "/10";
    var list = $("risk-factors");
    list.textContent = "";
    (r.risk_factors || []).forEach(function (factor) {
      var parts = factor.split(": ");
      var source = parts.length > 1 ? parts.shift() : "";
      list.appendChild(el("li", {}, [
        source ? el("span", { "class": "src", text: source }) : null,
        el("span", { text: parts.join(": ") })
      ]));
    });
    if (!list.children.length) list.appendChild(el("li", { text: "No risk factors in the available data." }));
    $("risk-note").textContent = "Heuristic score from the same logic the terminal report uses. A starting point for review, not a verdict.";

    var opsec = s.analyst.opsec;
    var opsecPill = $("opsec-pill");
    opsecPill.setAttribute("data-level", opsec.attribution_risk.toLowerCase());
    opsecPill.textContent = "ATTRIBUTION " + opsec.attribution_risk;
    facts($("opsec-facts"), [
      ["External IP", s.analyst.external_ip],
      ["Local IP", s.analyst.local_ip],
      ["Topology", topology(opsec)],
      ["VPN signal", vpnSignal(opsec)],
      ["Stealth level", opsec.stealth_level]
    ]);

    $("terminal-title").textContent = s.os === "Windows"
      ? "Windows PowerShell — " + s.terminal.command
      : "bash — " + s.terminal.command;
  }

  // ---------------------------------------------------------------------------
  // Comparison table
  // ---------------------------------------------------------------------------
  function renderCompare(selectedId) {
    var table = $("compare-table");
    table.textContent = "";
    var scenarios = DATA.scenarios;
    var head = el("tr", {}, [el("th", { scope: "col", text: "" })]);
    scenarios.forEach(function (s) {
      var th = el("th", { scope: "col", "class": s.id === selectedId ? "is-selected" : "" });
      th.appendChild(document.createTextNode(s.os + " · " + (s.vpn ? "VPN" : "direct")));
      th.appendChild(el("span", { "class": "col-sub", text: "Scan " + s.id }));
      head.appendChild(th);
    });
    table.appendChild(el("thead", {}, [head]));

    var rows = [
      ["Target sees", function (s) { return s.analyst.external_ip + (s.vpn ? " (VPN exit)" : " (own IP)"); }],
      ["Local IP", function (s) { return s.analyst.local_ip; }],
      ["Topology", function (s) { return topology(s.analyst.opsec); }],
      ["VPN signal", function (s) { return vpnSignal(s.analyst.opsec); }],
      ["Attribution risk", function (s) { return s.analyst.opsec.attribution_risk; }],
      ["Traceroute hops", function (s) {
        var np = s.report.network_path || {};
        return (np.responsive_hops != null ? np.responsive_hops : "?") + " of " + (np.total_hops != null ? np.total_hops : "?") + " responded";
      }],
      ["Edge IP resolved", function (s) { return (s.report.dns_info && s.report.dns_info.ipv4) || "n/a"; }],
      ["Modules complete", function (s) { return s.report.modules_successful.length + " / " + s.report.modules_executed.length; }],
      ["Domain risk", function (s) { return (s.report.overall_risk_level || "unknown").toUpperCase(); }],
      ["Scan duration", function (s) { return s.scan_duration_seconds.toFixed(1) + " s"; }]
    ];
    var body = el("tbody");
    rows.forEach(function (row) {
      var tr = el("tr", {}, [el("th", { scope: "row", text: row[0] })]);
      scenarios.forEach(function (s) {
        tr.appendChild(el("td", { "class": s.id === selectedId ? "is-selected" : "", text: String(row[1](s)) }));
      });
      body.appendChild(tr);
    });
    table.appendChild(body);
  }

  // ---------------------------------------------------------------------------
  // JSON tree (children render on first open to keep the DOM small)
  // ---------------------------------------------------------------------------
  function preview(value) {
    if (Array.isArray(value)) return "[" + value.length + (value.length === 1 ? " item]" : " items]");
    return "{" + Object.keys(value).length + (Object.keys(value).length === 1 ? " key}" : " keys}");
  }

  function scalarHtml(value) {
    if (value === null) return '<span class="j-null">null</span>';
    if (typeof value === "boolean") return '<span class="j-bool">' + value + "</span>";
    if (typeof value === "number") return '<span class="j-num">' + value + "</span>";
    return '<span class="j-str">' + escapeHtml(JSON.stringify(value)) + "</span>";
  }

  function treeNode(key, value) {
    var keyHtml = key === null ? "" : '<span class="j-key">' + escapeHtml(String(key)) + "</span>: ";
    if (value !== null && typeof value === "object") {
      var details = el("details");
      details.setAttribute("data-key", key === null ? "" : String(key));
      var summary = el("summary", { html: keyHtml + '<span class="j-meta">' + preview(value) + "</span>" });
      details.appendChild(summary);
      var filled = false;
      details.addEventListener("toggle", function () {
        if (!details.open || filled) return;
        filled = true;
        var entries = Array.isArray(value) ? value.map(function (v, i) { return [i, v]; }) : Object.keys(value).map(function (k) { return [k, value[k]]; });
        var frag = document.createDocumentFragment();
        entries.forEach(function (entry) { frag.appendChild(treeNode(entry[0], entry[1])); });
        if (!entries.length) frag.appendChild(el("div", { "class": "row j-meta", text: Array.isArray(value) ? "(empty list)" : "(no keys)" }));
        details.appendChild(frag);
      });
      return details;
    }
    return el("div", { "class": "row", html: keyHtml + scalarHtml(value) });
  }

  function renderJson(s) {
    var tree = $("json-tree");
    tree.textContent = "";
    var report = s.report;
    Object.keys(report).forEach(function (key) { tree.appendChild(treeNode(key, report[key])); });
    applyFilter();
  }

  function applyFilter() {
    var q = $("json-filter").value.trim().toLowerCase();
    Array.prototype.forEach.call($("json-tree").children, function (node) {
      var key = node.getAttribute("data-key");
      if (key === null) {
        var k = node.querySelector(".j-key");
        key = k ? k.textContent : "";
      }
      node.hidden = q !== "" && key.toLowerCase().indexOf(q) === -1;
    });
  }

  function copyJson() {
    var text = JSON.stringify(state.scenario.report, null, 2);
    var status = $("copy-status");
    function fallback() {
      var area = $("copy-fallback");
      area.value = text;
      area.removeAttribute("aria-hidden");
      area.select();
      var ok = false;
      try { ok = document.execCommand("copy"); } catch (err) { ok = false; }
      area.setAttribute("aria-hidden", "true");
      status.textContent = ok ? "Copied." : "Copy is blocked here. Select the text in the tree instead.";
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(function () {
        status.textContent = "Copied " + Math.round(text.length / 1024) + " KB of JSON.";
      }, fallback);
    } else {
      fallback();
    }
  }

  // ---------------------------------------------------------------------------
  // Scenario picker
  // ---------------------------------------------------------------------------
  function renderPicker() {
    var picker = $("scenario-picker");
    DATA.scenarios.forEach(function (s) {
      var btn = el("button", {
        type: "button",
        "class": "option",
        role: "radio",
        "aria-checked": "false",
        "data-id": s.id,
        id: "scenario-" + SLUGS[s.id]
      }, [
        el("span", { "class": "option-top" }, [
          el("span", { "class": "option-os", text: s.os }),
          el("span", { "class": "option-id", text: "Scan " + s.id })
        ]),
        el("span", { "class": "option-net", text: s.vpn ? "Through a VPN" + (s.vpn_country ? ", exit " + s.vpn_country : "") : "Direct connection" }),
        el("span", { "class": "option-meta", text: s.scan_duration_seconds.toFixed(1) + " s · " + s.analyst.opsec.attribution_risk.toLowerCase() + " attribution" })
      ]);
      btn.addEventListener("click", function () { selectScenario(s.id, true); });
      picker.appendChild(btn);
    });
    picker.addEventListener("keydown", function (event) {
      var keys = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 };
      if (!(event.key in keys)) return;
      event.preventDefault();
      var ids = DATA.scenarios.map(function (s) { return s.id; });
      var next = ids[(ids.indexOf(state.scenario.id) + keys[event.key] + ids.length) % ids.length];
      selectScenario(next, true);
      $("scenario-" + SLUGS[next]).focus();
    });
  }

  function selectScenario(id, fromUser) {
    var s = DATA.scenarios.filter(function (x) { return x.id === id; })[0] || DATA.scenarios[0];
    state.scenario = s;
    Array.prototype.forEach.call(document.querySelectorAll("#scenario-picker .option"), function (btn) {
      var on = btn.getAttribute("data-id") === s.id;
      btn.setAttribute("aria-checked", String(on));
      btn.tabIndex = on ? 0 : -1;
    });
    if (fromUser) {
      try { history.replaceState(null, "", "#" + SLUGS[s.id]); } catch (err) { /* sandboxed frames */ }
    }
    renderInspector(s);
    renderCompare(s.id);
    renderJson(s);
    restart();
  }

  function scenarioFromHash() {
    var token = (location.hash || "").replace("#", "");
    var match = Object.keys(SLUGS).filter(function (id) { return SLUGS[id] === token; })[0];
    return match || "A";
  }

  // ---------------------------------------------------------------------------
  // Wire up
  // ---------------------------------------------------------------------------
  if (!DATA || !DATA.scenarios || !DATA.scenarios.length) {
    terminal.textContent = "Demo data is missing. Run: python scripts/build_demo.py";
    return;
  }

  $("btn-play").addEventListener("click", function () { if (state.playing) pause(); else play(); });
  $("btn-restart").addEventListener("click", restart);
  $("btn-skip").addEventListener("click", function () {
    finish();
    state.followScroll = true;
    scrollToEnd();
  });
  $("speed").addEventListener("change", function () {
    if (state.playing) { pause(); play(); }
  });
  $("json-filter").addEventListener("input", applyFilter);
  $("btn-expand").addEventListener("click", function () {
    Array.prototype.forEach.call($("json-tree").children, function (node) {
      if (node.tagName === "DETAILS" && !node.hidden) node.open = true;
    });
  });
  $("btn-copy").addEventListener("click", copyJson);
  window.addEventListener("hashchange", function () { selectScenario(scenarioFromHash(), false); });

  renderPicker();
  selectScenario(scenarioFromHash(), false);
})();
